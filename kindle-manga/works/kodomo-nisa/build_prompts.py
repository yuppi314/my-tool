def render_page(pg):
    files = " ".join(f"`char_{c}.png`" for c in pg["ch"])
    ident = "\n".join(IDENT[c] for c in pg["ch"])
    shape, positions = TMPL[pg["t"]]

    out = [f"## ページ {pg['n']}／40", "", f"**添付**: {files}", "", "```"]
    out.append("【添付】キャラシートを参照してください。")
    out.append("")
    out.append("◆【絶対最優先】キャラクター外見")
    out.append("添付のキャラシートと100%同一の外見で描画してください。")
    out.append("髪色・髪型・服装・顔立ち・体型は、私の文章よりも添付画像を優先してください。")
    out.append(ident)
    out.append("")
    out.append(f"◆【出力サイズ】{SIZE} ※全ページ同一")
    out.append("")
    out.append(DRAW)
    out.append("")
    out.append(COLOR)
    out.append("")
    out.append(RULES)
    out.append("")
    out.append(f"◆【コマ構成】{shape}")
    out.append(positions)
    out.append("")
    if pg["prev"]:
        out.append("◆【直前ページからの接続】")
        out.append(f"前ページ最終コマ: {pg['prev']}")
        out.append("")
    out.append("◆【ストーリー】")
    for i, pn in enumerate(pg["panels"], 1):
        out.append("")
        label = "帯" if pn["pos"].startswith("帯") else f"コマ{i}"
        out.append(f"{label}（{pn['pos']}）")
        out.append(f"  情景: {pn['scene']}")
        for b in pn["bubbles"]:
            out.append(f"  セリフ: {b}")
        if pn["naration"]:
            out.append(f"  ナレーション: 四角い囲み（縦書き）—「{pn['naration']}」")
        if pn["box"]:
            out.append(f"  解説ボックス: コマ下辺の横長の白い囲み（横書き）—「{pn['box']}」")
        if pn["ono"]:
            out.append(f"  オノマトペ: {pn['ono']}")
        out.append(f"  背景: {pn['bg']}")
        if pn["note"]:
            out.append(f"  ※{pn['note']}")
        if pn["screen"]:
            out.append(f"  {pn['screen']}")
    out.append("```")
    out.append("")
    return "\n".join(out)


